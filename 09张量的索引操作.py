"""
案例：
    演示张量的索引操作
分类：
    简单行列索引
    列表索引
    布尔索引
    范围索引
    布尔索引
    多维索引
"""

import torch
torch.manual_seed(seed=24)

t1=torch.randint(1,10,(5,5))
#print(t1)

#简单行列索引&范围索引
print(t1[0,0])
print(t1[:,1:3])
print(t1[1::2,::2])

#列表索引
print(t1[[1,2],[3,4]]) #1行3列 2行4列 ——> 8,3

#多维索引 按照轴索引
t2=torch.randint(1,10,(2,3,4)) #——> 2,3,4切分
print(t2)
# (
# [0轴 2个元素
#   [1轴 3个元素
#       [2轴 4个元素
#           3, 4, 6, 5
#       ],
#       [8, 8, 8, 3],
#       [4, 9, 6, 7]
#   ],
#
#   [
#       [2, 8, 8, 5],
#       [6, 4, 2, 2],
#       [2, 7, 9, 4]
#    ]
#]
#)
print(t2[0,:,:]) # 0轴第一个元素
print(t2[:,0,:]) # 1轴第一个元素
print(t2[:,:,0]) # 2轴第一个元素
